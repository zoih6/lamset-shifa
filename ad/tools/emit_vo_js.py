#!/usr/bin/env python3
"""Emit film/scenes/vo_data.js: phrase-level VO timings for kinetic text (from docs/vo_word_timings.json)."""
import json, re, sys
d = json.load(open('docs/vo_word_timings.json'))
words = [w for s in d for w in s['words']]
def norm(w):
    w = re.sub(r'[\u064B-\u0652\u0640]', '', w)
    return w.replace('أ','ا').replace('إ','ا').replace('آ','ا')
NW = [norm(w['w']) for w in words]

PHRASES = [
 ('h1a','لأن كل خطوة صغيرة'), ('h1b','قد تكون بداية لتغيير كبير.'),
 ('h2a','نحن هنا لمساعدتك'), ('h2b','على الوصول إلى الأفضل.'),
 ('b1','بمركز لمسة شفاء'), ('b2','للعلاج الفيزيائي وإعادة التأهيل الطبي،'),
 ('p1','نؤمن أن لكل حالة احتياجاتها،'), ('p2','ولكل شخص قدراته'), ('p3','التي تستحق أن تكتشف وتنمى.'),
 ('sv0','نقدم مجموعة من الخدمات المتخصصة،'),
 ('sv1','العلاج الوظيفي،'), ('sv2','وتنمية المهارات،'), ('sv3','التدخل المبكر،'), ('sv4','وعلاج النطق واللغة،'),
 ('sv5','وصعوبات التعلم،'), ('sv6','والعلاج النفسي السلوكي،'), ('sv7','التطور الشامل السلوكي،'),
 ('sv8','إضافة إلى برامج متخصصة لاضطراب طيف التوحد.'),
 ('m1','نعمل بخطوات مدروسة'), ('m2','واهتمام حقيقي'), ('m3','لمساندة الأطفال والأسر'),
 ('m4','وتحقيق تطور ملموس'), ('m5','ينعكس على حياتهم اليومية.'),
 ('g1','لمسة شفاء،'), ('g2','لأن الشفاء ليس'), ('g2b','مجرد علاج،'), ('g3','بل رحلة نحو حياة أفضل.'),
 ('c1','زورونا في صنعاء'), ('c2','شارع الزبيري'), ('c3','جوار مستشفى سيبلاس،'), ('c4','أو تواصلوا معنا عبر الأرقام التالية:'),
]
# service names as displayed on the tiles (without the connective و / punctuation)
SERVICES = [
 ('t1','العلاج الوظيفي','hand'), ('t2','تنمية المهارات','sparkles'), ('t3','التدخل المبكر','baby'),
 ('t4','علاج النطق واللغة','message-circle'), ('t5','صعوبات التعلم','book-open'),
 ('t6','العلاج النفسي السلوكي','brain'), ('t7','التطور الشامل السلوكي','shapes'), ('t8','اضطراب طيف التوحد','puzzle'),
]
pos = 0
out = []
for pid, text in PHRASES:
    toks = [norm(x) for x in text.split()]
    # find the first index >= pos where the sequence matches (tolerating punct glued to words)
    found = None
    for i in range(pos, len(NW)):
        j, k = i, 0
        while j < len(NW) and k < len(toks):
            if NW[j] and toks[k] and (toks[k] in NW[j] or NW[j] in toks[k]): k += 1
            j += 1
        if k == len(toks): found = (i, j - 1); break
    if not found:
        print('!! not found:', text, file=sys.stderr); continue
    i0, i1 = found
    out.append(dict(id=pid, text=text, s=round(words[i0]['s'],2), e=round(words[i1]['e'],2)))
    pos = i1 + 1
# service tiles take their timing from the matching VO phrase (sv1..sv8), by index
SVT = [p for p in out if p['id'].startswith('sv') and p['id'] != 'sv0']
for n, (pid, label, ic) in enumerate(SERVICES):
    src = SVT[n]
    out.append(dict(id=pid, text=label, s=src['s'], e=SVT[n+1]['s'] if n+1 < len(SVT) else src['e'], icon=ic))

js = "// GENERATED by tools/emit_vo_js.py — phrase timings aligned to assets/vo/vo.aac (HUMAN script)\n"
js += "window.VO = " + json.dumps({'phrases': out}, ensure_ascii=False, indent=1) + ";\n"
js += "window.VO.P = id => (window.VO.phrases.find(p => p.id === id) || {s:0,e:0});\n"
open('film/scenes/vo_data.js','w',encoding='utf-8').write(js)
for p in out: print(f"{p['id']:4} {p['s']:6.2f}–{p['e']:6.2f}  {p['text']}")
